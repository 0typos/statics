#!/usr/bin/env bash

# Terminal descriptions compiled into libncurses. There is no terminfo
# database at run time: under any other TERM, set one of these.
NCURSES_FALLBACKS=ansi,dumb,linux,vt100,vt220,xterm,xterm-256color,screen,screen-256color,tmux,tmux-256color

build_ncurses() {
    echo "==> building ncurses (static libncurses for iftop and nethogs)"
    (
        cd "$WORK_DIR/ncurses" || exit
        local common=(
            --without-shared --with-normal --without-debug --without-profile
            --without-cxx --without-cxx-binding --without-ada
            --without-manpages --without-tests --disable-widec
            --without-gpm --disable-home-terminfo
        )
        # The fallback entries are C generated by tic and infocmp from
        # ncurses' own terminfo.src. Build those two for the host from this
        # same tree rather than trusting the builder's older ones to emit
        # the structures this version expects.
        mkdir host
        (
            cd host || exit
            CC=cc CFLAGS=-O1 ../configure "${common[@]}" >/dev/null
            run_make -C include
            run_make -C ncurses
            run_make -C progs tic infocmp
        ) || exit
        CC="$CC" AR="$AR" RANLIB="$RANLIB" ./configure \
            --build="$(cc -dumpmachine)" \
            --host="$AUTOCONF_HOST" \
            --prefix="$WORK_DIR/ncurses/install" \
            "${common[@]}" \
            --without-progs \
            --disable-database \
            --disable-db-install \
            --with-fallbacks="$NCURSES_FALLBACKS" \
            --with-tic-path="$PWD/host/progs/tic" \
            --with-infocmp-path="$PWD/host/progs/infocmp" \
            --with-build-cc=cc \
            CFLAGS="$STATIC_CFLAGS" \
            LDFLAGS="$STATIC_LDFLAGS"
        run_make -C include
        run_make -C ncurses
        make -s -C include install
        make -s -C ncurses install
    )
}
